export type StorageBody = Uint8Array | ReadableStream<Uint8Array>;

export interface StoredObjectInfo {
  key: string;
  size: number;
  contentType: string | null;
}

export interface StoredObject extends StoredObjectInfo {
  body: ReadableStream<Uint8Array>;
}

export interface PutObjectOptions {
  contentType: string;
  /** Required for streamed bodies so size limits and S3 uploads are exact. */
  contentLength?: number;
}

export interface DownloadUrlOptions {
  filename: string;
  contentType: string;
  expiresInSeconds: number;
}

/**
 * Provider-neutral object storage. Business code depends only on this interface; the
 * concrete driver is selected by configuration (STORAGE_DRIVER).
 *
 * Keys are opaque, generated by the application (never derived from user filenames).
 */
export interface ObjectStorage {
  readonly driver: "local" | "s3";
  put(key: string, body: StorageBody, options: PutObjectOptions): Promise<void>;
  get(key: string): Promise<StoredObject | null>;
  head(key: string): Promise<StoredObjectInfo | null>;
  delete(key: string): Promise<void>;
  /**
   * A short-lived direct download URL, or null when the driver cannot issue one; callers
   * then stream the object through an authorized route with get().
   */
  createDownloadUrl(key: string, options: DownloadUrlOptions): Promise<string | null>;
}

const OBJECT_KEY_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._-]*(\/[A-Za-z0-9][A-Za-z0-9._-]*)*$/;

export function assertValidObjectKey(key: string): void {
  if (key.length > 512 || !OBJECT_KEY_PATTERN.test(key) || key.split("/").some((segment) => segment === "..")) {
    throw new Error(`Invalid object key: ${JSON.stringify(key)}`);
  }
}
